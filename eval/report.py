"""Build eval/report.md from the evaluation's result files only (eval/answer_eval_protocol.md, section 8).

    python -m eval.report

Reads eval/results/evaluate.json (python -m eval.evaluate), eval/results/cutoff.json
(python -m eval.cutoff) and eval/results/judge_summary.json (python -m eval.judge summarize).
Every number shown is copied from those files; anything they don't contain yet is shown as
"not yet measured". Nothing is estimated.
"""
import argparse
import json
from pathlib import Path
from typing import Any

from eval.benchmark import ROOT

RESULTS_DIR = ROOT / "eval" / "results"
EVALUATE_JSON = RESULTS_DIR / "evaluate.json"
CUTOFF_JSON = RESULTS_DIR / "cutoff.json"
JUDGE_SUMMARY_JSON = RESULTS_DIR / "judge_summary.json"
REPORT_MD = ROOT / "eval" / "report.md"
NOT_YET = "not yet measured"


def _load(path: Path) -> dict[str, Any] | None:
    if not path.exists():
        return None
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def get(data: Any, *keys: str | int) -> Any:
    """data[k1][k2]..., or None when any level is missing."""
    for key in keys:
        if isinstance(data, dict) and isinstance(key, str):
            data = data.get(key)
        elif isinstance(data, list) and isinstance(key, int) and -len(data) <= key < len(data):
            data = data[key]
        else:
            return None
    return data


def num(value: Any, digits: int = 3) -> str:
    if isinstance(value, bool) or not isinstance(value, int | float):
        return NOT_YET
    return f"{value:.{digits}f}" if isinstance(value, float) else str(value)


def of(count: Any, total: Any) -> str:
    if isinstance(count, bool) or not isinstance(count, int) or not isinstance(total, int):
        return NOT_YET
    return f"{count} of {total}"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


OPINION = "*Opinion of the judge model ({model}), not ground truth.*"


def build(evaluate: dict[str, Any] | None, cutoff: dict[str, Any] | None, judge: dict[str, Any] | None) -> str:
    model = get(judge, "judge_model") or "gemini-3.8-flash"
    opinion = OPINION.format(model=model)
    lines = [
        "# Answer evaluation report",
        "",
        "Generated by `python -m eval.report` from `eval/results/*.json` only; every number is copied from those "
        "files, and anything not in them is shown as \"not yet measured\". Method: "
        "[`eval/answer_eval_protocol.md`](answer_eval_protocol.md). All resumes are synthetic.",
        "",
        "**Sample size.** 30 test questions, at most 33 judged answers and 40 judge-check items are too few to "
        "estimate rates precisely; a difference of one or two answers is within noise. Every number carries its n.",
        "",
        "## Provenance",
        "",
    ]
    lines += table(["Result file", "Commit", "Date"], [
        ["`eval/results/evaluate.json`", str(get(evaluate, "commit") or NOT_YET), str(get(evaluate, "date") or "")],
        ["`eval/results/cutoff.json`", str(get(cutoff, "commit") or NOT_YET), str(get(cutoff, "date") or "")],
        ["`eval/results/judge_summary.json`", "per item, in `eval/results/judge/`" if judge else NOT_YET, ""],
    ])
    files = get(evaluate, "answer_files") or []
    lines += ["", "Live answers used (protocol section 2):", ""]
    if files:
        lines += table(["File", "Commit", "Model", "Rows used", "/api/ask files changed since the first batch"],
                       [[f"`{f['file']}`", str(f.get("commit")), str(f.get("model")),
                         ", ".join(f.get("rows_used", [])) or "none",
                         ", ".join(f.get("ask_files_changed_since_first_batch", [])) or "none"] for f in files])
    else:
        lines.append(NOT_YET)

    lines += ["", "## 1. Outcomes of the benchmark questions (no LLM)", ""]
    counts = get(evaluate, "answers", "outcome_counts")
    outcomes = ["answered", "refused_grounding", "refused_similarity", "passages_only", "not_run"]
    lines += table(["Questions", *outcomes],
                   [[label, *[num(get(counts, kind, o)) for o in outcomes]]
                    for label, kind in (("answerable (30)", "positive"), ("unanswerable (3)", "negative"))])

    lines += ["", "## 2. Retrieval context passed to the LLM (no LLM)", "",
              "Vector search, k = 8, on SQLite exact search with local embeddings (protocol section 4.1).", ""]
    lines += table(["Questions", "n", "Context recall", "Context precision (ID-based)",
                    "Context precision (rank-aware)"],
                   [[label, num(get(evaluate, "context", key, "n")),
                     num(get(evaluate, "context", key, "context_recall")),
                     num(get(evaluate, "context", key, "context_precision_id")),
                     num(get(evaluate, "context", key, "context_precision_rank"))]
                    for label, key in (("benchmark (test set)", "benchmark"),
                                       ("held-out answerable", "heldout_answerable"))])
    check = get(evaluate, "ragas_check")
    if check is None:
        lines += ["", f"RAGAS cross-check: {NOT_YET}."]
    elif check.get("ragas_version") is None:
        lines += ["", "RAGAS cross-check: ragas was not installed, so the values are from our formulas only."]
    else:
        lines += ["", f"RAGAS {check['ragas_version']} cross-check of the ID-based metrics: precision "
                  f"{'agrees' if check.get('id_based_precision_agrees') else 'DISAGREES'}, recall "
                  f"{'agrees' if check.get('id_based_recall_agrees') else 'DISAGREES'}."]

    cv = get(evaluate, "citation_validity")
    lines += ["", "## 3. Citation validity of the live answers (no LLM)", "",
              "Share of citations that are labelled chunks; a lower bound on support (protocol section 4.2).", ""]
    lines += table(["Answers", "Citations", "Labelled", "Micro", "Macro"],
                   [[num(get(cv, "answers")), num(get(cv, "citations")), num(get(cv, "labelled")),
                     num(get(cv, "micro")), num(get(cv, "macro"))]])

    nf = get(evaluate, "not_found_similarity")
    lines += ["", "## 4. Not-found behaviour from similarity alone, current cutoff (no LLM)", ""]
    lines += table(["Cutoff", "Held-out unanswerable refused", "Held-out answerable refused"],
                   [[num(get(nf, "cutoff"), 2),
                     of(get(nf, "heldout_unanswerable", "refused"), get(nf, "heldout_unanswerable", "n")),
                     of(get(nf, "heldout_answerable", "refused"), get(nf, "heldout_answerable", "n"))]])

    lines += ["", "## 5. Cutoff recalibration on the held-out set (no LLM)", ""]
    if cutoff is None:
        lines.append(f"Proposed cutoff: {NOT_YET}.")
    else:
        lines += [f"Rule: {cutoff['rule']}", "",
                  f"Current {num(cutoff['current_cutoff'], 3)}, proposed **{num(cutoff['proposed_cutoff'], 4)}** "
                  f"({cutoff['reason']}). A proposal only: `ask.NOT_FOUND_THRESHOLD` changes in a reviewed commit.",
                  ""]
        rows = []
        for label, key, held_or_test in (("held-out, current", "heldout_at_current", "heldout"),
                                         ("held-out, proposed", "heldout_at_proposed", "heldout"),
                                         ("test set, current", "test_set_at_current", "test"),
                                         ("test set, proposed", "test_set_at_proposed", "test")):
            block = cutoff[key]
            a, u = (("heldout_answerable", "heldout_unanswerable") if held_or_test == "heldout"
                    else ("benchmark_answerable", "benchmark_negatives"))
            rows.append([label, num(block["cutoff"], 4), of(get(block, a, "refused"), get(block, a, "n")),
                         of(get(block, u, "refused"), get(block, u, "n"))])
        lines += table(["Set, cutoff", "Value", "Answerable refused", "Unanswerable refused"], rows)

    bench = get(judge, "benchmark")
    lines += ["", "## 6. RAGAS faithfulness and answer relevancy", "", opinion, ""]
    lines += table(["Metric", "Mean", "Scored", "Undefined", "Parse errors", "Answered rows"],
                   [[label, num(get(bench, key, "mean")), num(get(bench, key, "n_scored")),
                     num(get(bench, key, "undefined")), num(get(bench, key, "parse_errors")),
                     num(get(bench, "answered_rows"))]
                    for label, key in (("Faithfulness (cited passages)", "faithfulness"),
                                       ("Answer relevancy (strictness 1)", "answer_relevancy"))])

    rubric = get(bench, "rubric")
    lines += ["", "## 7. Rubric judge on the benchmark answers", "", opinion, ""]
    lines += table(["Measure", "Value"], [
        ["Answerable answers judged", num(get(rubric, "answerable_judged"))],
        ["Correct (2)", num(get(rubric, "correctness", "2"))],
        ["Partly correct (1)", num(get(rubric, "correctness", "1"))],
        ["Wrong (0)", num(get(rubric, "correctness", "0"))],
        ["Key-fact recall", NOT_YET if get(rubric, "key_fact_recall") is None else
         f"{num(get(rubric, 'key_fact_recall'))} "
         f"({of(get(rubric, 'key_facts_covered'), get(rubric, 'key_facts_required'))})"],
        ["Citation support 2 / 1 / 0", NOT_YET if rubric is None else
         " / ".join(num(get(rubric, "citation_support", s)) for s in "210")],
        ["Answers with an invented claim",
         of(get(rubric, "answers_with_invented_claims"), get(rubric, "rows_judged_ok"))],
        ["Unanswerable questions answered", num(get(rubric, "negatives_answered"))],
        ["Judge parse errors", num(get(rubric, "parse_errors"))],
    ])

    jc = get(judge, "judge_check")
    lines += ["", "## 8. Judge check on the held-out set", "", opinion, ""]
    lines += table(["Items", "Judge agrees"], [
        ["good answers (20)", of(get(jc, "good", "agreeing"), get(jc, "good", "judged"))],
        ["flawed: omission (4)", of(get(jc, "omission", "agreeing"), get(jc, "omission", "judged"))],
        ["flawed: invented claim (10)", of(get(jc, "invented_claim", "agreeing"), get(jc, "invented_claim", "judged"))],
        ["flawed: wrong citation (6)", of(get(jc, "wrong_citation", "agreeing"), get(jc, "wrong_citation", "judged"))],
        ["judge parse errors", num(get(jc, "parse_errors"))],
    ])

    lines += ["", "## 9. Per question (benchmark)", ""]
    rows_out = get(evaluate, "answers", "rows") or []
    validity = {r["id"]: r for r in get(evaluate, "citation_validity", "per_answer") or []}
    judged = {r["id"]: r for r in get(bench, "per_question") or []}
    if rows_out:
        body = []
        for r in rows_out:
            v, j = validity.get(r["id"], {}), judged.get(r["id"], {})
            body.append([r["id"], r["outcome"], str(r.get("commit") or ""),
                         of(v.get("labelled"), v.get("citations")) if v else "",
                         num(j.get("faithfulness")) if j else "", num(j.get("answer_relevancy")) if j else "",
                         num(j.get("correctness")) if j else "", num(j.get("citation_support")) if j else "",
                         num(j.get("invented_claims")) if j else ""])
        lines += table(["Question", "Outcome", "Answer commit", "Labelled citations", "Faithfulness",
                        "Relevancy", "Correctness", "Citation support", "Invented claims"], body)
        lines += ["", f"Faithfulness, relevancy and the rubric columns: {opinion[1:-1].lower()}"]
    else:
        lines.append(NOT_YET)

    lines += ["", "## 10. Gemini requests", ""]
    lines += table(["Judge runs", "Requests sent, retries included"],
                   [[num(get(judge, "requests", "runs")), num(get(judge, "requests", "sent"))]])
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.parse_args(argv)
    REPORT_MD.write_text(build(_load(EVALUATE_JSON), _load(CUTOFF_JSON), _load(JUDGE_SUMMARY_JSON)),
                         encoding="utf-8")
    print(f"wrote {REPORT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
